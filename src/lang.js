const GAME_LANG = { pl: 'pl_pl', en: 'en_us' };

function current() {
  try {
    return require('./store').load().settings.lang === 'en' ? 'en' : 'pl';
  } catch {
    return 'pl';
  }
}

function T(key, vars) {
  const table = MSG[current()] || MSG.pl;
  let s = table[key] !== undefined ? table[key] : (MSG.pl[key] !== undefined ? MSG.pl[key] : key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  return s;
}

module.exports = { T, GAME_LANG, current, MSG };
